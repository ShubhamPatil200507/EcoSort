def lookup_imagenet_waste(label: str) -> Optional[Dict[str, str]]:
    """
    Resolves an ImageNet label or multi-synonym prediction string
    into an EcoSort waste category and granular subtype.
    Uses exact key and whole-word matching to avoid spurious substring collisions.
    """
    if not label:
        return None
    label_lower = label.lower().strip()

    # 1. Exact direct key match
    if label_lower in IMAGENET_WASTE_MAP:
        return IMAGENET_WASTE_MAP[label_lower]

    # 2. Check each comma-separated synset synonym
    parts = [p.strip() for p in label_lower.split(",") if p.strip()]
    for p in parts:
        if p in IMAGENET_WASTE_MAP:
            return IMAGENET_WASTE_MAP[p]

    # 3. Whole token match (minimum length 4)
    for p in parts:
        if len(p) >= 4:
            for k, v in IMAGENET_WASTE_MAP.items():
                if k == p or (len(k) >= 5 and (k in p or p in k)):
                    return v

    return None
